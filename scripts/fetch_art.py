#!/usr/bin/env python3
"""Pick animated art for every character from Tenor and save it to art.json.

Run from anywhere: python3 scripts/fetch_art.py [character-id ...]
With no ids, every character without locked art is (re)picked. Then run scripts/build.py.

Art is hotlinked from Tenor, never copied into the repo; Vencord allows *.tenor.com.
To keep a pick forever, set "locked": true on its entry in art.json.
To use your own art instead, put files in assets/characters/<series>/<character>/ (see build.py);
files and roster.json entries always win over art.json.
"""

import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ART_FILE = ROOT / "art.json"
USER_AGENT = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
REQUEST_DELAY = 1.5

# Animated WebP is the same animation as the GIF at roughly a tenth of the size.
BACKGROUND_FORMATS = ("webp", "gif")
ICON_FORMATS = ("tinywebp", "tinygif", "webp", "gif")

AI_MARKERS = (
    "ai art", "aiart", "ai generated", "ai-generated", "ai animation", "ai anime", "ai video",
    "stable diffusion", "stablediffusion", "midjourney", "nijijourney", "niji journey",
    "novelai", "novel ai", "dall-e", "dalle", "sora", "kling", "pika labs", "runway gen",
    "generated by ai", "made with ai", "ai edit",
)
UNSAFE_MARKERS = ("nsfw", "lewd", "ecchi", "hentai", "r34", "rule34", "gore", "blood", "bloody", "porn")
REJECTED_FLAGS = {"sticker", "static"}
STOPWORDS = {"the", "of", "and", "no", "de", "d", "ko", "x"}

SERIES_SEARCH = {
    "frieren": "frieren",
    "uma-musume": "uma musume",
    "evangelion": "evangelion",
    "fate-grand-order": "fate",
    "honkai-star-rail": "honkai star rail",
    "march-comes-in-like-a-lion": "3gatsu no lion",
    "delicious-in-dungeon": "dungeon meshi",
}


def words(text):
    return [w for w in re.findall(r"[a-z0-9]+", text.lower()) if w not in STOPWORDS]


def search(query):
    url = f"https://tenor.com/search/{urllib.parse.quote(query.replace(' ', '-'))}-gifs"
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    html = urllib.request.urlopen(request, timeout=30).read().decode("utf-8", "replace")
    for script in re.findall(r"<script[^>]*>(.*?)</script>", html, re.S):
        if '"universal"' in script and '"results"' in script:
            state = json.loads(script)
            return [r for block in state["universal"]["search"].values() for r in block.get("results", [])]
    return []


def labels(result):
    """Uploader-written tags and titles; the place to look for who is in the GIF."""
    return " | ".join([result.get("h1_title", ""), result.get("long_title", ""), " , ".join(result.get("tags", []))]).lower()


def describe(result):
    """Labels plus Tenor's machine-written caption, which also catches on-screen text; used for filtering only."""
    return f"{labels(result)} | {result.get('content_description', '').lower()}"


def has_phrase(text, phrases):
    return any(re.search(rf"(?<![a-z0-9]){re.escape(p)}(?![a-z0-9])", text) for p in phrases)


def is_ai(result, char_name):
    if has_phrase(describe(result), AI_MARKERS):
        return True
    tags = {t.lower().strip() for t in result.get("tags", [])}
    # A bare "ai" tag means AI art, except for characters actually named Ai.
    return "ai" in tags and "ai" not in words(char_name)


def series_phrases(series):
    phrases = {series["name"].lower(), series["id"].replace("-", " "), SERIES_SEARCH.get(series["id"], "")}
    return {p for p in phrases if p} | {p.replace(" ", "") for p in phrases if p}


def judge(result, char_name, series, unique_words, rival_words):
    """None to reject, otherwise (names the series, names no co-star from the same series)."""
    if REJECTED_FLAGS & set(result.get("flags", [])):
        return None
    if has_phrase(describe(result), UNSAFE_MARKERS) or is_ai(result, char_name):
        return None
    text = labels(result)
    text_words = set(words(text))
    if not (has_phrase(text, [char_name.lower()]) or unique_words & text_words):
        return None
    return has_phrase(text, series_phrases(series)), not (rival_words & text_words)


def media(result, formats):
    for fmt in formats:
        entry = result.get("media_formats", {}).get(fmt)
        if entry and entry.get("url") and entry.get("dims"):
            return entry
    return None


def pick(results, char_name, series, unique_words, rival_words, require_series=False):
    candidates = []
    for result in results:
        verdict = judge(result, char_name, series, unique_words, rival_words) if media(result, BACKGROUND_FORMATS) else None
        if verdict and (verdict[0] or not require_series):
            candidates.append((sum(verdict), result))

    def aspect(r):
        w, h = media(r, BACKGROUND_FORMATS)["dims"]
        return w / h if h else 0

    wide = sorted(((s, r) for s, r in candidates if aspect(r) >= 1.3),
                  key=lambda sr: (sr[0], media(sr[1], BACKGROUND_FORMATS)["dims"][0]), reverse=True)
    background = wide[0][1] if wide else None

    rest = [(s, r) for s, r in candidates if r is not background]
    squareish = sorted(((s, r) for s, r in rest if 0.7 <= aspect(r) <= 1.4), key=lambda sr: sr[0], reverse=True)
    icon = (squareish or sorted(rest, key=lambda sr: sr[0], reverse=True) or [(0, None)])[0][1]
    return background, icon


def main():
    roster = json.loads((ROOT / "roster.json").read_text(encoding="utf-8"))
    art = json.loads(ART_FILE.read_text(encoding="utf-8")) if ART_FILE.exists() else {}
    only = set(sys.argv[1:])

    everyone = [c for s in roster["series"] for c in s["characters"]]
    word_owners = {}
    for char in everyone:
        for word in set(words(char["name"])):
            word_owners[word] = word_owners.get(word, 0) + 1

    def unique_words_of(char):
        # Family names like Hoshino or Uchiha are shared, so only words unique to one character identify them.
        return {w for w in words(char["name"]) if word_owners[w] == 1 and len(w) >= 2}

    todo = [(s, c) for s in roster["series"] for c in s["characters"]
            if (not only or c["id"] in only)
            and not art.get(c["id"], {}).get("locked")
            and not ("background" in c and "homeIcon" in c)]
    missing = []

    for index, (series, char) in enumerate(todo, 1):
        unique_words = unique_words_of(char)
        rival_words = set().union(*(unique_words_of(c) for c in series["characters"] if c is not char))
        query = f"{char['name']} {SERIES_SEARCH.get(series['id'], series['name'])}"
        try:
            background, icon = pick(search(query), char["name"], series, unique_words, rival_words)
            if not background and not icon:
                # A bare name search is noisy, so only trust results that also mention the series.
                time.sleep(REQUEST_DELAY)
                background, icon = pick(search(char["name"]), char["name"], series, unique_words, rival_words,
                                        require_series=True)
        except Exception as error:  # keep going; one failed search should not lose the rest
            print(f"[{index}/{len(todo)}] {char['id']}: search failed ({error})")
            missing.append(char["id"])
            continue

        entry = {}
        if background:
            entry["background"] = media(background, BACKGROUND_FORMATS)["url"]
            entry["backgroundSource"] = background["itemurl"]
        if icon:
            entry["homeIcon"] = media(icon, ICON_FORMATS)["url"]
            entry["homeIconSource"] = icon["itemurl"]
        if entry:
            art[char["id"]] = entry
        else:
            art.pop(char["id"], None)
            missing.append(char["id"])

        status = ", ".join(k for k in ("background", "homeIcon") if k in entry) or "nothing found"
        print(f"[{index}/{len(todo)}] {char['id']}: {status}")
        ART_FILE.write_text(json.dumps(dict(sorted(art.items())), indent=2) + "\n", encoding="utf-8")
        time.sleep(REQUEST_DELAY)

    if missing:
        print("No art found for: " + ", ".join(missing))


if __name__ == "__main__":
    main()
